static i2c_master_bus_handle_t s_bus;
static i2c_master_dev_handle_t s_dev;
static uint8_t s_fb[OLED_WIDTH * OLED_PAGES];
static bool s_ready;

static esp_err_t write_bytes(const uint8_t *data, size_t len)
{
    return i2c_master_transmit(s_dev, data, len, I2C_TIMEOUT_MS);
}

static esp_err_t write_cmd(uint8_t cmd)
{
    const uint8_t buf[2] = {0x00, cmd};
    return write_bytes(buf, sizeof(buf));
}

static esp_err_t write_cmds(const uint8_t *cmds, size_t n)
{
    esp_err_t err = ESP_OK;
    for (size_t i = 0; i < n && err == ESP_OK; i++) {
        err = write_cmd(cmds[i]);
    }
    return err;
}

static void fb_clear_band(int y0, int y1)
{
    for (int y = y0; y < y1; y++) {
        const uint8_t mask = (uint8_t)~(1u << (y % 8));
        uint8_t *row = s_fb + (y / 8) * OLED_WIDTH;
        for (int x = 0; x < OLED_WIDTH; x++) {
            row[x] &= mask;
        }
    }
}

static void fb_pixel(int x, int y)
{
    if ((unsigned)x >= OLED_WIDTH || (unsigned)y >= OLED_HEIGHT) {
        return;
    }
    s_fb[(y / 8) * OLED_WIDTH + x] |= (uint8_t)(1u << (y % 8));
}

/* Dibuja el caracter 8x8 estirado a 8x16 para llenar las dos mitades de la pantalla. */
static void fb_glyph(int x0, int y0, char ch)
{
    unsigned idx = 0;
    if ((unsigned char)ch >= 32 && (unsigned char)ch <= 126) {
        idx = (unsigned char)ch - 32;
    }
    for (int row = 0; row < 8; row++) {
        const uint8_t bits = s_font[idx][row];
        for (int col = 0; col < 8; col++) {
            if (bits & (1u << col)) {
                fb_pixel(x0 + col, y0 + row * 2);
                fb_pixel(x0 + col, y0 + row * 2 + 1);
            }
        }
    }
}

static esp_err_t flush(void)
{
    for (int page = 0; page < OLED_PAGES; page++) {
        const uint8_t window[] = {
            0x21, 0x00, 0x7F,
            0x22, (uint8_t)page, (uint8_t)page,
        };
        esp_err_t err = write_cmds(window, sizeof(window));
        if (err != ESP_OK) {
            return err;
        }
        uint8_t chunk[1 + OLED_WIDTH];
        chunk[0] = 0x40;
        memcpy(chunk + 1, s_fb + page * OLED_WIDTH, OLED_WIDTH);
        err = write_bytes(chunk, sizeof(chunk));
        if (err != ESP_OK) {
            return err;
        }
    }
    return ESP_OK;
}

esp_err_t oled_init(const oled_config_t *config)
{
    if (config == NULL || config->address < 0x08 || config->address > 0x77 || config->freq_hz == 0) {
        return ESP_ERR_INVALID_ARG;
    }
    if (s_ready) {
        return ESP_OK;
    }

    const i2c_master_bus_config_t bus_cfg = {
        .i2c_port = I2C_NUM_0,
        .sda_io_num = config->sda_gpio,
        .scl_io_num = config->scl_gpio,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    esp_err_t err = i2c_new_master_bus(&bus_cfg, &s_bus);
    if (err != ESP_OK) {
        return err;
    }

    err = i2c_master_probe(s_bus, config->address, I2C_TIMEOUT_MS);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "ningun OLED en 0x%02X (SDA=%d SCL=%d). Revisa VCC=3.3V, GND y la direccion (0x3C o 0x3D)",
                 config->address, config->sda_gpio, config->scl_gpio);
        i2c_del_master_bus(s_bus);
        s_bus = NULL;
        return err;
    }

    const i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = config->address,
        .scl_speed_hz = config->freq_hz,
    };
    err = i2c_master_bus_add_device(s_bus, &dev_cfg, &s_dev);
    if (err != ESP_OK) {
        i2c_del_master_bus(s_bus);
        s_bus = NULL;
        return err;
    }

    vTaskDelay(pdMS_TO_TICKS(100));
    static const uint8_t init_cmds[] = {
        0xAE,
        0xD5, 0x80,
        0xA8, 0x3F,
        0xD3, 0x00,
        0x40,
        0x8D, 0x14,
        0x20, 0x00,
        0xA1,
        0xC8,
        0xDA, 0x12,
        0x81, 0xCF,
        0xD9, 0xF1,
        0xDB, 0x40,
        0xA4,
        0xA6,
        0x2E,
        0xAF,
    };
    err = write_cmds(init_cmds, sizeof(init_cmds));
    if (err != ESP_OK) {
        goto fail;
    }

    memset(s_fb, 0, sizeof(s_fb));
    err = flush();
    if (err != ESP_OK) {
        goto fail;
    }

    s_ready = true;
    ESP_LOGI(TAG, "OLED SSD1306 128x64 en 0x%02X (SDA=%d SCL=%d)", config->address, config->sda_gpio, config->scl_gpio);
    return ESP_OK;

fail:
    i2c_master_bus_rm_device(s_dev);
    i2c_del_master_bus(s_bus);
    s_dev = NULL;
    s_bus = NULL;
    return err;
}

esp_err_t oled_write_line(uint8_t row, const char *text)
{
    if (!s_ready) {
        return ESP_ERR_INVALID_STATE;
    }
    if (row >= OLED_ROWS || text == NULL) {
        return ESP_ERR_INVALID_ARG;
    }

    const int y0 = (int)row * 32 + 8;
    fb_clear_band((int)row * 32, (int)row * 32 + 32);

    const size_t len = strlen(text);
    for (int col = 0; col < OLED_COLS; col++) {
        const char ch = ((size_t)col < len) ? text[col] : ' ';
        fb_glyph(col * 8, y0, ch);
    }
    return flush();
}
